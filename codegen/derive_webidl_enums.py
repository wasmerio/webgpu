#!/usr/bin/env python3
"""Derives spec/webidl_enums.json: the WebIDL string of every C enum value.

webgpu.json names enum values the C way (`BGRA8_unorm_srgb`); the JavaScript
API wants WebIDL strings (`"bgra8unorm-srgb"`), and the mapping is not regular
enough to compute from the C names alone. Dawn's dawn.json carries it (a naming
rule plus per-value `jsrepr` overrides), and Dawn's standard enums are checked
identical to upstream's, so values are matched by number.

    python3 codegen/derive_webidl_enums.py path/to/dawn/src/dawn/dawn.json

Run when the pinned spec gains enum values; the result is checked in.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spec import ROOT, Spec, pascal  # noqa: E402


def js_enum_case(name):
    chunks = name.split(" ")
    result = chunks[0].lower()
    for chunk in chunks[1:]:
        if not result[-1].isdigit():
            result += "-"
        result += chunk.lower()
    return result


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1]) as f:
        dawn = json.load(f)
    spec = Spec()
    by_name = {}
    for key, item in dawn.items():
        if isinstance(item, dict) and item.get("category") == "enum":
            by_name["".join(c[0].upper() + c[1:] for c in key.split(" "))] = item

    out = {"_comment": "Generated by codegen/derive_webidl_enums.py from Dawn's dawn.json. "
                       "WebIDL string of each C enum value, by enum and numeric value."}
    missing = []
    for enum in spec.enums:
        item = by_name.get(pascal(enum.name))
        if item is None or item.get("emscripten_no_enum_table"):
            continue
        ours = dict((value, name) for name, value in enum.entries)
        table = {}
        for value in item["values"]:
            if value.get("tags"):
                # A tagged value is an extension: Dawn numbers it in the tag's
                # own range (its `value` is an offset there, not the C value),
                # and upstream webgpu.h does not have it.
                continue
            number = value["value"]
            if number not in ours:
                continue
            if "jsrepr" in value:
                text = value["jsrepr"]
                if text == "undefined":
                    continue
                text = text.strip("'\"")
            else:
                text = js_enum_case(value["name"])
            table[str(number)] = text
        for number, name in sorted(ours.items()):
            if str(number) not in table and name not in ("undefined", "binding_not_used"):
                missing.append("%s.%s" % (enum.name, name))
        if table:
            out[pascal(enum.name)] = table
    path = os.path.join(ROOT, "spec", "webidl_enums.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=1, sort_keys=True)
        f.write("\n")
    print("wrote %s (%d enums)" % (os.path.relpath(path, ROOT), len(out) - 1))
    if missing:
        print("no WebIDL string known for: " + ", ".join(missing))


if __name__ == "__main__":
    main()
