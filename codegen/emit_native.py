"""The Dawn host's side of webgpu.h, from the same pinned webgpu.json:

- `src/dawn/ffi.gen.rs`: the native C API (types, layouts, functions), with
  compile-time checks of every size and offset on 64-bit targets;
- `src/dawn/layout_check.gen.c`: the same numbers as C static assertions,
  compiled by build.rs against the headers of the Dawn being linked;
- `src/dawn/lower.gen.rs`: decoded guest structs to native structs;
- `src/dawn/forward.gen.rs`: the imports that need nothing but forwarding,
  and calls to hand-written `manual_*` methods for the rest.

Dawn implements this exact header (its pinned webgpu-headers revision is the
one in spec/), so a decoded guest struct becomes a native one member by
member, and an import becomes the C function of the same name.
"""

from spec import pascal, singular, snake
from emit_rust import field_type, strict_enum

BANNER = "// Generated by codegen/gen.py from spec/webgpu.json and spec/abi.json. Do not edit.\n"

NATIVE_PRIM = {
    "bool": "WGPUBool", "uint16": "u16", "uint32": "u32", "uint64": "u64", "usize": "usize",
    "int16": "i16", "int32": "i32", "float32": "f32", "nullable_float32": "f32",
    "float64": "f64", "float64_supertype": "f64",
}
# (size, align) on a 64-bit target
NATIVE_LAYOUT = {
    "bool": (4, 4), "uint16": (2, 2), "uint32": (4, 4), "uint64": (8, 8), "usize": (8, 8),
    "int16": (2, 2), "int32": (4, 4), "float32": (4, 4), "nullable_float32": (4, 4),
    "float64": (8, 8), "float64_supertype": (8, 8),
}
RUST_KEYWORDS = {"type", "loop", "match", "ref", "in", "mod", "move", "use", "fn", "impl", "self",
                 "override", "final", "struct", "enum", "where", "async", "await", "dyn", "box"}

# Imports implemented by hand, as `manual_<name>` methods of the Dawn host,
# because they need host policy rather than a forward: the GPU memory budget,
# stable queue handles, surfaces (the guest names a target, the embedder
# decides what it is), mapped ranges and uploads that read guest memory, and
# instance-wide state. Functions whose arguments cannot be forwarded (an out
# struct, a pointer into guest memory) are added automatically.
MANUAL = {
    "wgpuCreateInstance", "wgpuGetInstanceLimits", "wgpuHasInstanceFeature",
    "wgpuInstanceCreateSurface",
    "wgpuDeviceCreateBuffer", "wgpuDeviceCreateTexture", "wgpuDeviceDestroy",
    "wgpuDeviceGetQueue", "wgpuQueueRelease",
    "wgpuBufferUnmap", "wgpuBufferDestroy",
    # WGPU_WHOLE_SIZE means the rest of the source here, as in the browser
    # host; Dawn's C API takes only a real size.
    "wgpuCommandEncoderCopyBufferToBuffer",
    "wgpuTextureDestroy",
    "wgpuSurfaceConfigure", "wgpuSurfacePresent", "wgpuSurfaceUnconfigure",
    "wgpuSurfaceSetLabel",
}
# Extension structs a guest may chain that must never reach the GPU library:
# native window handles cannot come from a guest's memory, the WASIX canvas
# selector is the host's own business, and SPIR-V is refused so that a
# program meets the same shading language on every host.
REFUSED_EXTENSIONS = {
    "surface_source_android_native_window": "native window handles",
    "surface_source_metal_layer": "native window handles",
    "surface_source_wayland_surface": "native window handles",
    "surface_source_windows_HWND": "native window handles",
    "surface_source_XCB_window": "native window handles",
    "surface_source_xlib_window": "native window handles",
    "shader_source_SPIRV": "SPIR-V shader sources (use WGSL)",
    "wasix_surface_source_canvas": "a WASIX surface source here",
}


# Object arrays whose elements may be null although webgpu.json does not say
# so: WebGPU lets a pipeline layout leave a bind group slot empty.
NULLABLE_ELEMENTS = {"pipeline_layout_descriptor.bind_group_layouts"}

# Binding layout members webgpu.h defaults when a guest leaves them
# `undefined`. Dawn's frontend applies only the view dimension defaults, and
# refuses an undefined type here, so the host lowers these to their default.
# (`binding not used`, which marks the member unused, stays as it is.)
UNDEFINED_DEFAULTS = {
    "buffer_binding_layout.type": "uniform",
    "sampler_binding_layout.type": "filtering",
    "texture_binding_layout.sample_type": "float",
    "storage_texture_binding_layout.access": "write_only",
}


def ident(name):
    return "r#" + name if name in RUST_KEYWORDS else name


def nbase(ty):
    if ty.kind == "prim":
        return NATIVE_PRIM[ty.base]
    if ty.kind == "string":
        return "WGPUStringView"
    if ty.kind == "void":
        return "c_void"
    if ty.kind == "callback":
        return "WGPU%sCallbackInfo" % pascal(ty.base)
    return "WGPU" + pascal(ty.base)


def ntype(ty):
    base = nbase(ty)
    if ty.pointer == "immutable":
        return "*const " + base
    if ty.pointer == "mutable":
        return "*mut " + base
    return base


def array_ptr(ty):
    return ("*mut " if ty.pointer == "mutable" else "*const ") + nbase(ty)


class Layouts(object):
    """Struct layouts on a 64-bit target: what the C compiler lays out."""

    def __init__(self, spec):
        self.spec = spec
        self.cache = {}

    def member(self, ty):
        if ty.array:
            return 16, 8
        if ty.pointer:
            return 8, 8
        if ty.kind == "prim":
            return NATIVE_LAYOUT[ty.base]
        if ty.kind == "string":
            return 16, 8
        if ty.kind == "enum":
            return 4, 4
        if ty.kind in ("bitflag", "object"):
            return 8, 8
        if ty.kind == "callback":
            return (40 if self.spec.callback_by_name[ty.base].style == "callback_mode" else 32), 8
        if ty.kind == "struct":
            size, align, _ = self.of(self.spec.struct_by_name[ty.base])
            return size, align
        raise SystemExit("no native layout for " + ty.raw)

    def of(self, s):
        """(size, align, [(c member name, offset)]) of a struct."""
        if s.name in self.cache:
            return self.cache[s.name]
        off, align, fields = 0, 1, []
        if s.has_chain_root:
            fields.append(("nextInChain", 0))
            off, align = 8, 8
        elif s.kind == "extension":
            fields.append(("chain", 0))
            off, align = 16, 8
        for m in s.members:
            size, al = self.member(m.ty)
            off = (off + al - 1) // al * al
            if m.ty.array:
                fields.append((m.c_count_name, off))
                fields.append((m.c_name, off + 8))
            else:
                fields.append((m.c_name, off))
            off += size
            align = max(align, al)
        size = (off + align - 1) // align * align
        self.cache[s.name] = (size, align, fields)
        return self.cache[s.name]


def native_structs(spec):
    # The WASIX extension's structs are the host's own; Dawn does not know them.
    return [s for s in spec.structs if not s.is_extension_api]


# -- ffi.gen.rs ----------------------------------------------------------------

def fn_params(fn):
    """[(rust name, rust type)] of a C function, arrays expanded."""
    out = []
    if fn.role == "free_members":
        return [("value", "WGPU" + pascal(fn.owner))]
    if fn.owner is not None:
        out.append((ident(snake(fn.owner)), "WGPU" + pascal(fn.owner)))
    for a in fn.args:
        name = ident(snake(a.name))
        if a.array:
            out.append((snake(singular(a.name)) + "_count", "usize"))
            out.append((name, array_ptr(a)))
        else:
            out.append((name, ntype(a)))
    if fn.callback:
        out.append(("callback_info", "WGPU%sCallbackInfo" % pascal(fn.callback)))
    return out


def fn_return(fn):
    if fn.callback:
        return "WGPUFuture"
    if fn.role == "get_proc_address":
        return "WGPUProc"
    if fn.returns is None:
        return None
    return ntype(fn.returns)


def emit_ffi(spec):
    layouts = Layouts(spec)
    out = [BANNER]
    out.append("//! The native webgpu.h, as Dawn implements it.\n")
    out.append("#![allow(non_camel_case_types, non_snake_case, dead_code, clippy::missing_safety_doc)]\n")
    out.append("use std::ffi::{c_char, c_void};\n")
    out.append("pub type WGPUBool = u32;")
    out.append("pub type WGPUFlags = u64;")
    out.append("pub type WGPUProc = Option<unsafe extern \"C\" fn()>;\n")
    out.append("/// `WGPU_STRLEN`: a string view whose length is this is NUL-terminated (or null).")
    out.append("pub const WGPU_STRLEN: usize = usize::MAX;\n")
    out.append("#[repr(C)]\n#[derive(Clone, Copy, Debug)]")
    out.append("pub struct WGPUStringView {\n    pub data: *const c_char,\n    pub length: usize,\n}")
    out.append("impl Default for WGPUStringView {\n    fn default() -> Self {\n"
               "        Self { data: std::ptr::null(), length: WGPU_STRLEN }\n    }\n}\n")
    out.append("#[repr(C)]\n#[derive(Clone, Copy, Debug)]")
    out.append("pub struct WGPUChainedStruct {\n    pub next: *mut WGPUChainedStruct,\n    pub sType: u32,\n}\n")
    out.append("// Objects are opaque pointers.")
    for o in spec.objects:
        n = "WGPU" + pascal(o)
        out.append("#[repr(C)]\npub struct %sImpl {\n    _private: [u8; 0],\n}" % n)
        out.append("pub type %s = *mut %sImpl;" % (n, n))
    out.append("")
    out.append("// Enums are 32-bit values, bitflags 64-bit (`WGPUFlags`). The numbers are")
    out.append("// those of `crate::abi::enums`, which the guest uses too.")
    for e in spec.enums:
        out.append("pub type %s = u32;" % e.c_name)
    for b in spec.bitflags:
        out.append("pub type %s = WGPUFlags;" % b.c_name)
    out.append("")
    for c in spec.callbacks:
        args = ["%s: %s" % (ident(snake(a.name)), ntype(a)) for a in c.args]
        args += ["userdata1: *mut c_void", "userdata2: *mut c_void"]
        out.append("pub type WGPU%sCallback = Option<unsafe extern \"C\" fn(%s)>;" % (pascal(c.name), ", ".join(args)))
        out.append("#[repr(C)]\n#[derive(Clone, Copy)]")
        out.append("pub struct WGPU%sCallbackInfo {" % pascal(c.name))
        out.append("    pub nextInChain: *mut WGPUChainedStruct,")
        if c.style == "callback_mode":
            out.append("    pub mode: WGPUCallbackMode,")
        out.append("    pub callback: WGPU%sCallback," % pascal(c.name))
        out.append("    pub userdata1: *mut c_void,\n    pub userdata2: *mut c_void,\n}")
        out.append("impl Default for WGPU%sCallbackInfo {\n    fn default() -> Self {\n"
                   "        // SAFETY: null pointers and no callback.\n"
                   "        unsafe { std::mem::zeroed() }\n    }\n}" % pascal(c.name))
    out.append("")

    checks = []
    for s in native_structs(spec):
        size, _, fields = layouts.of(s)
        out.append("/// `%s`" % s.c_name)
        out.append("#[repr(C)]\n#[derive(Clone, Copy)]")
        out.append("pub struct %s {" % s.c_name)
        if s.has_chain_root:
            out.append("    pub nextInChain: *mut WGPUChainedStruct,")
        elif s.kind == "extension":
            out.append("    pub chain: WGPUChainedStruct,")
        for m in s.members:
            if m.ty.array:
                out.append("    pub %s: usize," % ident(m.c_count_name))
                out.append("    pub %s: %s," % (ident(m.c_name), array_ptr(m.ty)))
            else:
                out.append("    pub %s: %s," % (ident(m.c_name), ntype(m.ty)))
        out.append("}")
        out.append("impl Default for %s {\n    fn default() -> Self {\n"
                   "        // SAFETY: every member of a webgpu.h struct has a valid all-zero value.\n"
                   "        unsafe { std::mem::zeroed() }\n    }\n}" % s.c_name)
        checks.append("    assert!(size_of::<%s>() == %d);" % (s.c_name, size))
        for name, offset in fields:
            checks.append("    assert!(std::mem::offset_of!(%s, %s) == %d);" % (s.c_name, ident(name), offset))
    out.append("")
    out.append("// What codegen computed for a 64-bit target, which layout_check.gen.c also")
    out.append("// asserts against the C headers being linked: if both hold, Rust and C agree.")
    out.append("#[cfg(target_pointer_width = \"64\")]\nconst _: () = {")
    out += checks
    out.append("};\n")

    out.append("unsafe extern \"C\" {")
    for fn in spec.functions:
        if fn.is_extension_api:
            continue
        params = ", ".join("%s: %s" % p for p in fn_params(fn))
        ret = fn_return(fn)
        out.append("    pub fn %s(%s)%s;" % (fn.c_name, params, "" if ret is None else " -> " + ret))
    out.append("}\n")

    out.append("/// The type of a GPU object behind a guest handle.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum Kind {")
    for o in spec.objects:
        out.append("    %s," % pascal(o))
    out.append("}\n")
    out.append("impl Kind {")
    for op, verb in (("add_ref", "AddRef"), ("release", "Release")):
        out.append("    /// `wgpu*%s` for an object of this type." % verb)
        out.append("    pub unsafe fn %s(self, raw: *mut c_void) {" % op)
        out.append("        // SAFETY: the caller passes a live object of this type.")
        out.append("        unsafe {")
        out.append("            match self {")
        for o in spec.objects:
            n = pascal(o)
            out.append("                Kind::%s => wgpu%s%s(raw as WGPU%s)," % (n, n, verb, n))
        out.append("            }\n        }\n    }")
    out.append("}")
    return "\n".join(out) + "\n", layouts


def emit_layout_check(spec, layouts):
    out = ["/* Generated by codegen/gen.py from spec/webgpu.json and spec/abi.json. Do not edit. */",
           "/* What src/dawn/ffi.gen.rs assumes of the native API (struct layouts, enum",
           "   values, function prototypes), checked against the webgpu.h of the Dawn",
           "   being linked. Compiled by build.rs. */",
           "#include <stddef.h>", "#include <stdint.h>", "#include <webgpu/webgpu.h>", "",
           "#if UINTPTR_MAX == UINT64_MAX"]
    for s in native_structs(spec):
        size, _, fields = layouts.of(s)
        out.append("_Static_assert(sizeof(%s) == %d, \"%s\");" % (s.c_name, size, s.c_name))
        for name, offset in fields:
            if name == "chain":
                continue
            out.append("_Static_assert(offsetof(%s, %s) == %d, \"%s.%s\");" % (s.c_name, name, offset, s.c_name, name))
    out.append("#endif")
    out.append("")
    out.append("/* Enum values: the bindings pass the guest's numbers through. */")
    for e in spec.enums:
        for entry, value in e.entries:
            out.append("_Static_assert(%s == 0x%X, \"%s\");" % (e.c_entry(entry), value, e.c_entry(entry)))
    out.append("")
    out.append("/* Bitflags are static consts, which only clang folds in a static assertion. */")
    out.append("#if defined(__clang__)")
    out.append("#pragma clang diagnostic ignored \"-Wgnu-folding-constant\"")
    for b in spec.bitflags:
        for entry, value in b.entries:
            name = "%s_%s" % (b.c_name, pascal(entry))
            out.append("_Static_assert(%s == 0x%XULL, \"%s\");" % (name, value, name))
    out.append("#endif")
    out.append("")
    out.append("/* Every function the bindings declare has the prototype they assume. */")
    out.append("#if defined(__GNUC__)")
    out.append("#define SAME_TYPE(f) _Static_assert(__builtin_types_compatible_p(__typeof__(f), check_##f), #f)")
    for fn in spec.functions:
        if fn.is_extension_api:
            continue
        out.append("typedef %s;" % fn.c_decl("check_" + fn.c_name))
        out.append("SAME_TYPE(%s);" % fn.c_name)
    out.append("#endif")
    out.append("")
    out.append("/* Something for the archive to hold. */")
    out.append("int wasmer_webgpu_dawn_layout_checked(void) { return 1; }")
    return "\n".join(out) + "\n"


# -- lower.gen.rs --------------------------------------------------------------

def lower_member(spec, s, m, field):
    """Statements filling native member(s) of `n` from decoded `self.<field>`."""
    ty = m.ty
    where = "%s.%s" % (s.c_name, m.c_name)
    if field_type(spec, ty) is None:
        return []  # callbacks and output strings: left zero
    if ty.kind == "string":
        if ty.base == "nullable_string":
            return ["n.%s = l.opt_str(self.%s.as_deref());" % (ident(m.c_name), field)]
        return ["n.%s = l.str(&self.%s);" % (ident(m.c_name), field)]
    if ty.array:
        count, ptr = ident(m.c_count_name), ident(m.c_name)
        if ty.kind == "struct":
            call = "l.array(&self.%s)?" % field
        elif strict_enum(spec, ty):
            call = "l.enums(&self.%s)" % field
        elif ty.kind == "object":
            nullable = "%s.%s" % (s.name, m.name) in NULLABLE_ELEMENTS
            call = "l.objects(Kind::%s, &self.%s, \"%s\", %s)?" % (
                pascal(ty.base), field, where, "true" if nullable else "false")
        else:
            call = "l.u32s(&self.%s)" % field
        return ["let (count, ptr) = %s;" % call,
                "n.%s = count;" % count,
                "n.%s = ptr.cast();" % ptr]
    if ty.pointer:
        if ty.kind == "struct" and ty.pointer == "immutable":
            return ["n.%s = l.boxed(self.%s.as_deref())?;" % (ident(m.c_name), field)]
        return ["if self.%s != 0 {" % field,
                "    return Err(Invalid::Unsupported(\"%s\"));" % where,
                "}"]
    if ty.kind == "prim":
        if ty.base == "bool":
            return ["n.%s = WGPUBool::from(self.%s);" % (ident(m.c_name), field)]
        if ty.base == "usize":
            return ["n.%s = usize_from_guest(self.%s);" % (ident(m.c_name), field)]
        return ["n.%s = self.%s;" % (ident(m.c_name), field)]
    if ty.kind == "enum":
        default = UNDEFINED_DEFAULTS.get("%s.%s" % (s.name, m.name))
        if default:
            values = dict(spec.enum_by_name[ty.base].entries)
            assert values["undefined"] == 1, ty.base
            return ["n.%s = undefined_as(self.%s.as_u32(), 0x%X); // %s" % (
                ident(m.c_name), field, values[default], default)]
        if strict_enum(spec, ty):
            return ["n.%s = self.%s.as_u32();" % (ident(m.c_name), field)]
        return ["n.%s = self.%s;" % (ident(m.c_name), field)]
    if ty.kind == "bitflag":
        return ["n.%s = self.%s;" % (ident(m.c_name), field)]
    if ty.kind == "object":
        return ["n.%s = l.object(Kind::%s, self.%s, \"%s\", %s)?.cast();" % (
            ident(m.c_name), pascal(ty.base), field, where, "true" if ty.optional else "false")]
    if ty.kind == "struct":
        return ["n.%s = self.%s.lower(l)?;" % (ident(m.c_name), field)]
    if ty.kind == "void":
        return ["if self.%s != 0 {" % field,
                "    return Err(Invalid::Unsupported(\"%s\"));" % where,
                "}"]
    raise SystemExit("cannot lower " + where)


def emit_lower(spec):
    out = [BANNER]
    out.append("//! Decoded guest structs (`crate::abi::structs`) to native ones (`super::ffi`).\n")
    out.append("#![allow(clippy::field_reassign_with_default, unused_mut, unused_variables)]\n")
    out.append("use super::ffi::*;")
    out.append("use super::lower::{Invalid, Lower, Lowering, undefined_as, usize_from_guest};")
    out.append("use crate::abi::AbiEnum;")
    out.append("use crate::abi::structs as g;\n")
    extensions = [s for s in native_structs(spec) if s.kind == "extension"]

    out.append("/// Links the native forms of a decoded `nextInChain` list.")
    out.append("pub(super) fn chain(l: &mut Lowering<'_>, chain: &g::Chain) -> Result<*mut WGPUChainedStruct, Invalid> {")
    out.append("    let mut next = std::ptr::null_mut();")
    out.append("    for item in chain.items.iter().rev() {")
    out.append("        next = match item {")
    for s in spec.structs:
        if s.kind != "extension":
            continue
        if s.name in REFUSED_EXTENSIONS:
            out.append("            g::Chained::%s(_) => return Err(Invalid::Unsupported(\"%s\"))," % (
                s.rust_name, REFUSED_EXTENSIONS[s.name]))
            continue
        out.append("            g::Chained::%s(value) => {" % s.rust_name)
        out.append("                let mut native = value.lower(l)?;")
        out.append("                native.chain.next = next;")
        out.append("                l.store(native).cast()")
        out.append("            }")
    out.append("        };")
    out.append("    }")
    out.append("    Ok(next)")
    out.append("}\n")

    for s in native_structs(spec):
        if s.name in REFUSED_EXTENSIONS:
            continue
        fields = []
        for m in s.members:
            if field_type(spec, m.ty) is not None:
                fields.append(m)
        out.append("impl Lower for g::%s {" % s.rust_name)
        out.append("    type Native = %s;" % s.c_name)
        out.append("    fn lower(&self, l: &mut Lowering<'_>) -> Result<%s, Invalid> {" % s.c_name)
        out.append("        let mut n = %s::default();" % s.c_name)
        if s.has_chain_root:
            out.append("        n.nextInChain = chain(l, &self.chain)?;")
        elif s.kind == "extension":
            out.append("        n.chain.sType = 0x%X;" % s.stype)
        for m in s.members:
            for line in lower_member(spec, s, m, snake(m.name)):
                out.append("        " + line)
        out.append("        Ok(n)")
        out.append("    }\n}\n")
    out += emit_raise(spec)
    return "\n".join(out) + "\n"


def raise_member(spec, m, field):
    """Statement filling decoded `v.<field>` from native `n`, for host-written structs."""
    ty = m.ty
    if field_type(spec, ty) is None or ty.array or ty.pointer:
        return None
    src = "n.%s" % ident(m.c_name)
    if ty.kind == "prim":
        if ty.base == "bool":
            return "v.%s = %s != 0;" % (field, src)
        if ty.base == "usize":
            return "v.%s = u32::try_from(%s).unwrap_or(u32::MAX);" % (field, src)
        return "v.%s = %s;" % (field, src)
    if ty.kind == "enum":
        if strict_enum(spec, ty):
            return "v.%s = AbiEnum::from_u32(%s).unwrap_or_default();" % (field, src)
        return "v.%s = %s;" % (field, src)
    if ty.kind == "bitflag":
        return "v.%s = %s;" % (field, src)
    if ty.kind == "struct" and ty.base in RAISED:
        return "v.%s = raise_%s(&%s);" % (field, ty.base, src)
    return None  # objects: the caller turns them into handles


# Host-written structs the Dawn host fills from a native struct. (Instance
# limits are the host's own.)
RAISED = ["limits", "compatibility_mode_limits", "surface_texture"]


def emit_raise(spec):
    out = ["/// Native structs the host writes back to the guest, decoded form (objects left 0)."]
    for name in RAISED:
        s = spec.struct_by_name[name]
        out.append("pub(super) fn raise_%s(n: &%s) -> g::%s {" % (name, s.c_name, s.rust_name))
        out.append("    let mut v = g::%s::default();" % s.rust_name)
        for m in s.members:
            line = raise_member(spec, m, snake(m.name))
            if line:
                out.append("    " + line)
        out.append("    v\n}\n")
    return out


# -- forward.gen.rs ------------------------------------------------------------

def needs_manual(fn):
    if fn.c_name in MANUAL or fn.is_extension_api:
        return True
    for a in fn.args:
        if a.kind == "struct" and a.pointer == "mutable":
            return True
        if not a.array and a.kind not in ("struct", "object", "string") and (a.pointer or a.kind == "void"):
            return True
    return False


def forward_arg(spec, fn, a):
    """(statements, [native argument expressions]) for one decoded trait argument.
    A statement's `TRY(e)` is `e` with its error reported and the call ended."""
    n = snake(a.name)
    where = "%s.%s" % (fn.c_name, a.name)
    if a.array:
        if a.kind == "struct":
            call = "TRY(l.array(%s))" % n
        elif strict_enum(spec, a):
            call = "l.enums(%s)" % n
        elif a.kind == "object":
            call = "TRY(l.objects(Kind::%s, %s, \"%s\", false))" % (pascal(a.base), n, where)
        else:
            call = "l.u32s(%s)" % n
        return (["let (%s_count, %s) = %s;" % (n, n, call)], ["%s_count" % n, "%s.cast()" % n])
    if a.kind == "string":
        if a.base == "nullable_string":
            return ([], ["l.opt_str(%s)" % n])
        return ([], ["l.str(%s)" % n])
    if a.kind == "struct":
        if a.optional:
            return (["let %s = TRY(l.lower_opt(%s));" % (n, n)], [n])
        return (["let %s = TRY(l.lower_ptr(%s));" % (n, n)], [n])
    if a.kind == "object":
        return (["let %s = TRY(l.object(Kind::%s, %s, \"%s\", %s));" % (
            n, pascal(a.base), n, where, "true" if a.optional else "false")], ["%s.cast()" % n])
    if a.kind == "enum":
        return ([], ["%s.as_u32()" % n] if strict_enum(spec, a) else [n])
    if a.kind == "bitflag":
        return ([], [n])
    if a.kind == "prim":
        if a.base == "bool":
            return ([], ["WGPUBool::from(%s)" % n])
        if a.base == "usize":
            return ([], ["usize_from_guest(%s)" % n])
        return ([], [n])
    raise SystemExit("cannot forward " + where)


def trait_sig(spec, fn):
    """(rust params after cx, return type) exactly as emit_rust declares them."""
    from emit_rust import lower_arg, lower_return
    sig = []
    if fn.owner is not None and fn.role != "free_members":
        sig.append("%s: Handle" % snake(fn.owner))
    for a in fn.args:
        sig.append("%s: %s" % (snake(a.name), lower_arg(spec, a).trait_ty))
    _, ret, _ = lower_return(spec, fn)
    return sig, ret


def emit_forward(spec):
    out = [BANNER]
    out.append("//! The Dawn host's imports. Most forward to the C function of the same name;")
    out.append("//! the rest call the hand-written `manual_*` method of the same name.\n")
    out.append("#![allow(unused_variables, unused_imports, clippy::unnecessary_cast)]\n")
    out.append("use super::ffi::{self, Kind, WGPUBool};")
    out.append("use super::lower::{Lowering, usize_from_guest};")
    out.append("use super::Host;")
    out.append("use crate::abi::api::*;")
    out.append("use crate::abi::enums::*;")
    out.append("use crate::abi::structs::*;")
    out.append("use crate::abi::{AbiEnum, Cx, Handle, OutPtr};\n")

    traits, order = {}, []
    manual = []
    for fn in spec.raw_import_functions():
        name = (pascal(fn.owner) if fn.owner else "Global") + "Api"
        if name not in traits:
            traits[name] = []
            order.append(name)
        sig, ret = trait_sig(spec, fn)
        decl = "    fn %s(&self, cx: &mut Cx<'_>%s)%s {" % (
            fn.rust_name, "".join(", " + p for p in sig), "" if ret == "()" else " -> " + ret)
        body = traits[name]
        body.append(decl)
        names = [p.split(":")[0] for p in sig]
        if needs_manual(fn):
            manual.append(fn.c_name)
            body.append("        self.manual_%s(cx%s)" % (fn.rust_name, "".join(", " + n for n in names)))
            body.append("    }")
            continue
        recv = snake(fn.owner)
        kind = "Kind::" + pascal(fn.owner)
        if fn.role == "add_ref":
            body.append("        self.add_ref_handle(%s, %s);" % (recv, kind))
            body.append("    }")
            continue
        if fn.role == "release":
            body.append("        self.release_handle(%s, %s);" % (recv, kind))
            body.append("    }")
            continue
        failed = "Status::Error" if ret == "Status" else "Default::default()"
        if ret == "()":
            failed = ""
        body.append("        let Some(this) = self.object(%s, %s) else {" % (recv, kind))
        body.append("            return %s;" % failed if failed else "            return;")
        body.append("        };")
        native_args = ["this.raw.cast()"]
        stmts = []
        for a in fn.args:
            st, exprs = forward_arg(spec, fn, a)
            stmts += st
            native_args += exprs
        uses_l = any("l." in x for x in stmts + native_args)
        if uses_l:
            body.append("        let %sl = Lowering::new(self, Some(&this));" % (
                "mut " if any("TRY(" in x or "l." in x for x in stmts + native_args) else ""))
        for st in stmts:
            if "TRY(" in st:
                head, rest = st.split("TRY(", 1)
                inner, tail = rest.rsplit(")", 1)
                body.append("        %smatch %s {" % (head, inner))
                body.append("            Ok(value) => value,")
                body.append("            Err(error) => {")
                body.append("                l.fail(\"%s\", error);" % fn.c_name)
                body.append("                return%s;" % ((" " + failed) if failed else ""))
                body.append("            }")
                body.append("        }%s" % tail)
            else:
                body.append("        " + st)
        call = "ffi::%s(%s)" % (fn.c_name, ", ".join(native_args))
        r = fn.returns
        body.append("        // SAFETY: live objects, and native values that outlive the call.")
        plain = r is not None and not (r.kind == "object" or (r.kind == "enum" and strict_enum(spec, r))
                                       or (r.kind == "prim" and r.base == "bool"))
        if r is None:
            body.append("        unsafe { %s };" % call)
        elif plain:
            body.append("        unsafe { %s }" % call)
        else:
            body.append("        let r = unsafe { %s };" % call)
            if r.kind == "object":
                body.append("        self.adopt(Kind::%s, r.cast(), &this, %s)" % (pascal(r.base), recv))
            elif r.kind == "enum" and strict_enum(spec, r):
                body.append("        %s::from_u32(r).unwrap_or(%s)" % (
                    pascal(r.base), "Status::Error" if ret == "Status" else "Default::default()"))
            elif r.kind == "prim" and r.base == "bool":
                body.append("        r != 0")
        body.append("    }")

    for name in order:
        out.append("impl %s for Host {" % name)
        out += traits[name]
        out.append("}\n")
    return "\n".join(out) + "\n", manual
