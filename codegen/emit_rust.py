"""Host-side Rust outputs: enums, wasm32 struct readers, the `Api` trait with
its import glue, and the import signature table shared with the JS backend."""

from spec import PRIMS, pascal, rust_variant, singular, snake

BANNER = "// Generated by codegen/gen.py from spec/webgpu.json and spec/abi.json. Do not edit.\n"

RUST_PRIM = {
    "bool": "bool", "uint16": "u16", "uint32": "u32", "uint64": "u64", "usize": "u32",
    "int16": "i16", "int32": "i32", "float32": "f32", "nullable_float32": "f32",
    "float64": "f64", "float64_supertype": "f64",
}
WASM_RUST = {"i32": "u32", "i64": "u64", "f32": "f32", "f64": "f64"}


def const_name(s):
    return s.upper()


# -- enums ---------------------------------------------------------------------

def emit_enums(spec):
    out = [BANNER]
    out.append("use super::{AbiEnum, AbiError, AbiResult};\n")
    for e in spec.enums:
        name = e.rust_name
        zero = [n for n, v in e.entries if v == 0]
        default = rust_variant(zero[0] if zero else e.entries[0][0])
        out.append("/// `%s`" % e.c_name)
        out.append("#[repr(u32)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
        out.append("pub enum %s {" % name)
        for entry, value in e.entries:
            out.append("    %s = 0x%X," % (rust_variant(entry), value))
        out.append("}")
        out.append("impl Default for %s {\n    fn default() -> Self {\n        Self::%s\n    }\n}" % (name, default))
        out.append("impl AbiEnum for %s {" % name)
        out.append("    const NAME: &'static str = \"%s\";" % e.c_name)
        out.append("    fn from_u32(value: u32) -> Option<Self> {")
        out.append("        Some(match value {")
        for entry, value in e.entries:
            out.append("            0x%X => Self::%s," % (value, rust_variant(entry)))
        out.append("            _ => return None,")
        out.append("        })\n    }")
        out.append("    fn as_u32(self) -> u32 {\n        self as u32\n    }\n}")
        out.append("impl %s {" % name)
        out.append("    pub fn from_abi(value: u32) -> AbiResult<Self> {")
        out.append("        Self::from_u32(value).ok_or(AbiError::InvalidEnum { ty: Self::NAME, value })")
        out.append("    }\n}\n")
    for b in spec.bitflags:
        out.append("/// `%s` (a `uint64_t` in the C API)" % b.c_name)
        out.append("pub mod %s {" % snake(b.name))
        for entry, value in b.entries:
            out.append("    pub const %s: u64 = 0x%X;" % (const_name(entry), value))
        out.append("}\n")
    out.append("/// Sentinel constants.")
    for name, value in spec.constants:
        if value == "nan":
            out.append("pub const %s: f32 = f32::NAN;" % const_name(name))
        elif value == "uint64_max":
            out.append("pub const %s: u64 = u64::MAX;" % const_name(name))
        else:  # uint32_max, usize_max: both 32 bits in the guest
            out.append("pub const %s: u32 = u32::MAX;" % const_name(name))
    out.append("")
    out.append("/// sType values declared by webgpu_wasix.h.")
    for name, value in sorted(spec.extension_stypes.items()):
        out.append("pub const STYPE_%s: u32 = 0x%08X;" % (const_name(name), value))
    for value, name in sorted(spec.stype_aliases.items()):
        out.append("pub const STYPE_%s_ALIAS: u32 = 0x%08X;" % (const_name(name), value))
    return "\n".join(out) + "\n"


# -- structs -------------------------------------------------------------------

def strict_enum(spec, ty):
    return ty.kind == "enum" and ty.base not in spec.lenient_enums


def field_type(spec, ty):
    """Rust type of a struct member in the decoded form, or None if it is not decoded."""
    if ty.kind == "callback":
        return None
    if ty.kind == "string":
        if ty.base == "out_string":
            return None
        return "Option<String>" if ty.base == "nullable_string" else "String"
    if ty.array:
        if ty.kind == "struct":
            return "Vec<%s>" % pascal(ty.base)
        if strict_enum(spec, ty):
            return "Vec<%s>" % pascal(ty.base)
        return "Vec<u32>"
    if ty.pointer:
        if ty.kind == "struct" and ty.pointer == "immutable":
            return "Option<Box<%s>>" % pascal(ty.base)
        return "u32"
    if ty.kind == "prim":
        return RUST_PRIM[ty.base]
    if ty.kind == "enum":
        return pascal(ty.base) if strict_enum(spec, ty) else "u32"
    if ty.kind == "bitflag":
        return "u64"
    if ty.kind in ("object", "void"):
        return "u32"
    if ty.kind == "struct":
        return pascal(ty.base)
    raise SystemExit("no field type for " + ty.raw)


def read_expr(spec, ty, o):
    if ty.kind == "string":
        fn = "read_nullable_string" if ty.base == "nullable_string" else "read_string"
        return "mem.%s(rd_u32(&b, %d), rd_u32(&b, %d))?" % (fn, o, o + 4)
    if ty.array:
        count, ptr = "rd_u32(&b, %d)" % o, "rd_u32(&b, %d)" % (o + 4)
        if ty.kind == "struct":
            return "mem.read_array(%s, %s)?" % (ptr, count)
        if strict_enum(spec, ty):
            return "mem.read_enum_array(%s, %s)?" % (ptr, count)
        return "mem.read_u32_array(%s, %s)?" % (ptr, count)
    if ty.pointer:
        if ty.kind == "struct" and ty.pointer == "immutable":
            return "mem.read_opt(rd_u32(&b, %d))?" % o
        return "rd_u32(&b, %d)" % o
    if ty.kind == "prim":
        return {
            "bool": "rd_u32(&b, %d) != 0",
            "uint16": "rd_u16(&b, %d)",
            "int16": "rd_u16(&b, %d) as i16",
            "uint32": "rd_u32(&b, %d)",
            "usize": "rd_u32(&b, %d)",
            "int32": "rd_u32(&b, %d) as i32",
            "uint64": "rd_u64(&b, %d)",
            "float32": "f32::from_bits(rd_u32(&b, %d))",
            "nullable_float32": "f32::from_bits(rd_u32(&b, %d))",
            "float64": "f64::from_bits(rd_u64(&b, %d))",
            "float64_supertype": "f64::from_bits(rd_u64(&b, %d))",
        }[ty.base] % o
    if ty.kind == "enum":
        if strict_enum(spec, ty):
            return "%s::from_abi(rd_u32(&b, %d))?" % (pascal(ty.base), o)
        return "rd_u32(&b, %d)" % o
    if ty.kind == "bitflag":
        return "rd_u64(&b, %d)" % o
    if ty.kind in ("object", "void"):
        return "rd_u32(&b, %d)" % o
    if ty.kind == "struct":
        return "%s::read(mem, ptr.wrapping_add(%d))?" % (pascal(ty.base), o)
    raise SystemExit("no reader for " + ty.raw)


def write_stmt(spec, ty, o, field):
    """Statement storing a scalar member into the byte buffer `b`, or None."""
    if ty.array or ty.pointer or ty.kind in ("string", "callback", "void", "struct"):
        return None
    if ty.kind == "prim":
        return {
            "bool": "wr_u32(&mut b, %d, u32::from(self.%s));",
            "uint16": "wr_u16(&mut b, %d, self.%s);",
            "int16": "wr_u16(&mut b, %d, self.%s as u16);",
            "uint32": "wr_u32(&mut b, %d, self.%s);",
            "usize": "wr_u32(&mut b, %d, self.%s);",
            "int32": "wr_u32(&mut b, %d, self.%s as u32);",
            "uint64": "wr_u64(&mut b, %d, self.%s);",
            "float32": "wr_u32(&mut b, %d, self.%s.to_bits());",
            "nullable_float32": "wr_u32(&mut b, %d, self.%s.to_bits());",
            "float64": "wr_u64(&mut b, %d, self.%s.to_bits());",
            "float64_supertype": "wr_u64(&mut b, %d, self.%s.to_bits());",
        }[ty.base] % (o, field)
    if ty.kind == "enum":
        if strict_enum(spec, ty):
            return "wr_u32(&mut b, %d, self.%s.as_u32());" % (o, field)
        return "wr_u32(&mut b, %d, self.%s);" % (o, field)
    if ty.kind == "bitflag":
        return "wr_u64(&mut b, %d, self.%s);" % (o, field)
    if ty.kind == "object":
        return "wr_u32(&mut b, %d, self.%s);" % (o, field)
    return None


def chain_extensions(spec, root):
    return [s for s in spec.structs if s.kind == "extension" and root.name in s.extends]


def emit_structs(spec):
    out = [BANNER]
    out.append("use super::enums::*;")
    out.append("#[allow(unused_imports)]")
    out.append("use super::{rd_u16, rd_u32, rd_u64, wr_u16, wr_u32, wr_u64, AbiEnum, AbiError, AbiResult, "
               "GuestMemory, GuestRead, GuestWrite};\n")
    out.append("/// Longest `nextInChain` list the host follows.")
    out.append("pub const MAX_CHAIN_LENGTH: usize = 16;\n")

    extensions = [s for s in spec.structs if s.kind == "extension"]
    out.append("/// One decoded extension struct of a `nextInChain` list.")
    out.append("#[derive(Clone, Debug)]\npub enum Chained {")
    for s in extensions:
        out.append("    %s(%s)," % (s.rust_name, s.rust_name))
    out.append("}\n")
    out.append("/// Where one chained struct lives in guest memory, for chains the host writes into.")
    out.append("#[derive(Clone, Copy, Debug)]\npub struct ChainLink {\n    pub s_type: u32,\n    pub ptr: u32,\n}\n")
    out.append("/// A decoded `nextInChain` list.")
    out.append("#[derive(Clone, Debug, Default)]\npub struct Chain {\n    pub items: Vec<Chained>,\n"
               "    pub links: Vec<ChainLink>,\n}\n")
    out.append("impl Chain {")
    out.append("    /// Follows the list starting at `ptr`, rejecting any sType not in `allowed`.")
    out.append("    pub fn read(mem: &GuestMemory<'_>, mut ptr: u32, allowed: &[u32]) -> AbiResult<Self> {")
    out.append("        let mut chain = Chain::default();")
    out.append("        while ptr != 0 {")
    out.append("            if chain.links.len() >= MAX_CHAIN_LENGTH {")
    out.append("                return Err(AbiError::ChainTooLong);")
    out.append("            }")
    out.append("            let header = mem.read_bytes::<8>(ptr)?;")
    out.append("            let s_type = rd_u32(&header, 4);")
    out.append("            if !allowed.contains(&s_type) {")
    out.append("                return Err(AbiError::UnknownSType(s_type));")
    out.append("            }")
    out.append("            chain.links.push(ChainLink { s_type, ptr });")
    out.append("            chain.items.push(Chained::read(mem, s_type, ptr)?);")
    out.append("            ptr = rd_u32(&header, 0);")
    out.append("        }")
    out.append("        Ok(chain)")
    out.append("    }")
    for s in extensions:
        out.append("    pub fn %s(&self) -> Option<&%s> {" % (snake(s.name), s.rust_name))
        out.append("        self.items.iter().find_map(|item| match item {")
        out.append("            Chained::%s(value) => Some(value)," % s.rust_name)
        if len(extensions) > 1:
            out.append("            _ => None,")
        out.append("        })\n    }")
    out.append("    /// Guest address of the chained struct with this sType, if present.")
    out.append("    pub fn link(&self, s_type: u32) -> Option<u32> {")
    out.append("        self.links.iter().find(|link| link.s_type == s_type).map(|link| link.ptr)")
    out.append("    }")
    out.append("}\n")
    out.append("impl Chained {")
    out.append("    fn read(mem: &GuestMemory<'_>, s_type: u32, ptr: u32) -> AbiResult<Self> {")
    out.append("        Ok(match s_type {")
    for s in extensions:
        codes = ["0x%X" % s.stype] + ["0x%X" % v for v, n in sorted(spec.stype_aliases.items()) if n == s.name]
        out.append("            %s => Self::%s(%s::read(mem, ptr)?)," % (" | ".join(codes), s.rust_name, s.rust_name))
    out.append("            _ => return Err(AbiError::UnknownSType(s_type)),")
    out.append("        })\n    }\n}\n")

    written = set(spec.abi["host_written_structs"])
    for s in spec.structs:
        fields = []
        if s.has_chain_root:
            fields.append(("chain", "Chain", None))
        for m in s.members:
            t = field_type(spec, m.ty)
            if t is not None:
                fields.append((snake(m.name), t, m))
        out.append("/// `%s`: %d bytes, align %d on wasm32." % (s.c_name, s.size, s.align))
        out.append("#[derive(Clone, Debug, Default)]")
        if fields:
            out.append("pub struct %s {" % s.rust_name)
            for name, t, _ in fields:
                out.append("    pub %s: %s," % (name, t))
            out.append("}")
        else:
            out.append("pub struct %s {}" % s.rust_name)
        if s.kind == "extension":
            out.append("impl %s {\n    pub const S_TYPE: u32 = 0x%X;\n}" % (s.rust_name, s.stype))
        if s.has_chain_root:
            allowed = []
            for e in chain_extensions(spec, s):
                allowed.append("0x%X" % e.stype)
                allowed += ["0x%X" % v for v, n in sorted(spec.stype_aliases.items()) if n == e.name]
            out.append("impl %s {" % s.rust_name)
            out.append("    /// sTypes accepted in this struct's chain.")
            out.append("    pub const CHAIN: &'static [u32] = &[%s];" % ", ".join(allowed))
            out.append("}")
        out.append("impl GuestRead for %s {" % s.rust_name)
        out.append("    const SIZE: u32 = %d;" % s.size)
        out.append("    const ALIGN: u32 = %d;" % s.align)
        out.append("    fn read(mem: &GuestMemory<'_>, ptr: u32) -> AbiResult<Self> {")
        inits = []
        for name, t, m in fields:
            if m is None:
                inits.append("            chain: Chain::read(mem, rd_u32(&b, 0), Self::CHAIN)?,")
            else:
                inits.append("            %s: %s," % (name, read_expr(spec, m.ty, m.offset)))
        if any("&b" in init for init in inits):
            out.append("        let b = mem.read_bytes::<%d>(ptr)?;" % s.size)
        else:
            # Nothing is decoded from the bytes themselves; still fault on a bad pointer.
            out.append("        mem.read_bytes::<%d>(ptr)?;" % s.size)
        out.append("        Ok(Self {")
        out += inits
        out.append("        })\n    }\n}")
        if s.name in written:
            out.append("impl GuestWrite for %s {" % s.rust_name)
            out.append("    /// Stores the scalar members, leaving `nextInChain` and padding as the guest set them.")
            out.append("    fn write(&self, mem: &GuestMemory<'_>, ptr: u32) -> AbiResult<()> {")
            out.append("        let mut b = mem.read_bytes::<%d>(ptr)?;" % s.size)
            nested = []
            for m in s.members:
                stmt = write_stmt(spec, m.ty, m.offset, snake(m.name))
                if stmt:
                    out.append("        " + stmt)
                elif m.ty.kind == "struct" and not m.ty.array and not m.ty.pointer and m.ty.base in written:
                    nested.append(m)
            out.append("        mem.write_bytes(ptr, &b)?;")
            for m in nested:
                out.append("        self.%s.write(mem, ptr.wrapping_add(%d))?;" % (snake(m.name), m.offset))
            out.append("        Ok(())\n    }\n}")
        out.append("")
    return "\n".join(out) + "\n"


# -- API trait and import glue --------------------------------------------------

class Lowered(object):
    """How one C parameter appears in the wasm signature, the glue, and the trait."""

    def __init__(self, wasm, prelude, trait_ty, call):
        self.wasm = wasm  # [(name, rust wasm type)]
        self.prelude = prelude  # statements run before the call (may use `?`)
        self.trait_ty = trait_ty  # type in the trait method signature
        self.call = call  # expression passed to the trait method


def lower_arg(spec, a):
    n = snake(a.name)
    if a.array:
        cn = snake(singular(a.name)) + "_count"
        wasm = [(cn, "u32"), (n, "u32")]
        if a.kind == "struct":
            t = pascal(a.base)
            return Lowered(wasm, ["let %s = cx.mem.read_array::<%s>(%s, %s)?;" % (n, t, n, cn)], "&[%s]" % t, "&" + n)
        if strict_enum(spec, a):
            t = pascal(a.base)
            return Lowered(wasm, ["let %s = cx.mem.read_enum_array::<%s>(%s, %s)?;" % (n, t, n, cn)],
                           "&[%s]" % t, "&" + n)
        return Lowered(wasm, ["let %s = cx.mem.read_u32_array(%s, %s)?;" % (n, n, cn)], "&[u32]", "&" + n)
    if a.kind == "string":
        if a.base == "nullable_string":
            return Lowered([(n, "u32")], ["let %s = cx.mem.read_nullable_string_view(%s)?;" % (n, n)],
                           "Option<&str>", n + ".as_deref()")
        return Lowered([(n, "u32")], ["let %s = cx.mem.read_string_view(%s)?;" % (n, n)], "&str", "&" + n)
    if a.kind == "struct":
        t = pascal(a.base)
        if a.pointer == "mutable":
            return Lowered([(n, "u32")], [], "OutPtr<%s>" % t, "OutPtr::new(%s)" % n)
        if a.optional:
            return Lowered([(n, "u32")], ["let %s = cx.mem.read_opt::<%s>(%s)?;" % (n, t, n)],
                           "Option<&%s>" % t, n + ".as_deref()")
        return Lowered([(n, "u32")], ["let %s = cx.mem.read_required::<%s>(%s, \"%s\")?;" % (n, t, n, a.name)],
                       "&%s" % t, "&" + n)
    if a.pointer or a.kind == "void":
        return Lowered([(n, "u32")], [], "u32", n)
    if a.kind == "object":
        return Lowered([(n, "u32")], [], "Handle", n)
    if a.kind == "enum":
        if strict_enum(spec, a):
            t = pascal(a.base)
            return Lowered([(n, "u32")], ["let %s = %s::from_abi(%s)?;" % (n, t, n)], t, n)
        return Lowered([(n, "u32")], [], "u32", n)
    if a.kind == "bitflag":
        return Lowered([(n, "u64")], [], "u64", n)
    if a.kind == "prim":
        w = WASM_RUST[PRIMS[a.base][3]]
        t = RUST_PRIM[a.base]
        if a.base == "bool":
            return Lowered([(n, "u32")], [], "bool", n + " != 0")
        if a.base in ("int32", "int16", "uint16"):
            return Lowered([(n, "u32")], [], t, "%s as %s" % (n, t))
        return Lowered([(n, w)], [], t, n)
    raise SystemExit("cannot lower argument " + a.raw)


def lower_return(spec, fn):
    """(wasm rust type or None, trait return type, conversion applied to `r`)."""
    r = fn.returns
    if r is None:
        return None, "()", None
    if r.kind == "object":
        return "u32", "Handle", "r"
    if r.kind == "enum":
        if strict_enum(spec, r):
            return "u32", pascal(r.base), "r.as_u32()"
        return "u32", "u32", "r"
    if r.kind == "bitflag":
        return "u64", "u64", "r"
    if r.kind == "prim":
        if r.base == "bool":
            return "u32", "bool", "u32::from(r)"
        w = WASM_RUST[PRIMS[r.base][3]]
        t = RUST_PRIM[r.base]
        return w, t, "r" if w == t else "r as " + w
    raise SystemExit("cannot lower return of " + fn.c_name)


def emit_api(spec):
    """One trait per object (so a backend can implement each in its own file),
    the glue that decodes wasm arguments for them, and the registration."""
    import os
    defaults = os.environ.get("WGPU_GEN_DEFAULTS") == "1"

    out = [BANNER]
    out.append("use wasmer::{AsStoreMut, Exports, Function, FunctionEnv, FunctionEnvMut, RuntimeError};\n")
    out.append("use super::enums::*;\nuse super::structs::*;")
    out.append("use super::{AbiEnum, AbiResult, Cx, Handle, OutPtr};")
    out.append("use crate::env::WebGpuEnv;\nuse crate::native::enter;\n")

    traits, order = {}, []  # trait name -> method lines
    glue, reg = [], []

    def trait_of(owner):
        name = (pascal(owner) if owner else "Global") + "Api"
        if name not in traits:
            traits[name] = []
            order.append(name)
        return traits[name]

    def body(ret):
        if not defaults:
            return ";"
        return " {\n        let _ = cx;\n        crate::host::unimplemented(\"%s\")\n    }"

    for fn in spec.raw_import_functions():
        params = []  # wasm params
        prelude, sig, call = [], [], []
        if fn.owner is not None and fn.role != "free_members":
            recv = snake(fn.owner)
            params.append((recv, "u32"))
            sig.append("%s: Handle" % recv)
            call.append(recv)
        for a in fn.args:
            low = lower_arg(spec, a)
            params += low.wasm
            prelude += low.prelude
            sig.append("%s: %s" % (snake(a.name), low.trait_ty))
            call.append(low.call)
        wasm_ret, trait_ret, conv = lower_return(spec, fn)

        methods = trait_of(fn.owner)
        methods.append("    /// `%s`" % fn.c_name)
        decl = "    fn %s(&self, cx: &mut Cx<'_>%s)%s" % (
            fn.rust_name, "".join(", " + s for s in sig), "" if trait_ret == "()" else " -> " + trait_ret)
        if defaults:
            unused = "".join("        let _ = %s;\n" % s.split(":")[0] for s in sig)
            methods.append(decl + " {\n        let _ = cx;\n" + unused +
                           "        crate::host::unimplemented(\"%s\")\n    }" % fn.c_name)
        else:
            methods.append(decl + ";")

        glue_name = "import_" + fn.rust_name
        args = "".join(", %s: %s" % p for p in params)
        glue.append("fn %s(mut env: FunctionEnvMut<'_, WebGpuEnv>%s) -> Result<%s, RuntimeError> {" % (
            glue_name, args, wasm_ret or "()"))
        glue.append("    enter(&mut env, \"%s\", |host, cx| {" % fn.c_name)
        for p in prelude:
            glue.append("        " + p)
        invoke = "host.%s(cx%s)" % (fn.rust_name, "".join(", " + c for c in call))
        if conv is None:
            glue.append("        %s;" % invoke)
            glue.append("        Ok(())")
        elif conv == "r":
            glue.append("        Ok(%s)" % invoke)
        else:
            glue.append("        let r = %s;" % invoke)
            glue.append("        Ok(%s)" % conv)
        glue.append("    })\n}\n")
        reg.append("    exports.insert(\"%s\", Function::new_typed_with_env(store, env, %s));" % (fn.c_name, glue_name))

    traits["ShimApi"] = []
    order.append("ShimApi")
    for s in spec.special_imports:
        name = s["name"]
        params = [(snake(n), WASM_RUST[t]) for n, t in s["params"]]
        ret = {"i32": "i32", "i64": "u64", None: None}[s["result"]]
        methods = traits["ShimApi"]
        if s.get("doc"):
            methods.append("    /// %s" % s["doc"])
        decl = "    fn %s(&self, cx: &mut Cx<'_>%s) -> AbiResult<%s>" % (
            name, "".join(", %s: %s" % p for p in params), ret or "()")
        if defaults:
            unused = "".join("        let _ = %s;\n" % n for n, _ in params)
            methods.append(decl + " {\n        let _ = cx;\n" + unused +
                           "        Ok(crate::host::unimplemented(\"%s\"))\n    }" % name)
        else:
            methods.append(decl + ";")
        glue.append("fn import_%s(mut env: FunctionEnvMut<'_, WebGpuEnv>%s) -> Result<%s, RuntimeError> {" % (
            name, "".join(", %s: %s" % p for p in params), ret or "()"))
        glue.append("    enter(&mut env, \"%s\", |host, cx| host.%s(cx%s))" % (
            name, name, "".join(", " + n for n, _ in params)))
        glue.append("}\n")
        reg.append("    exports.insert(\"%s\", Function::new_typed_with_env(store, env, import_%s));" % (name, name))

    out.append("// One trait per object, so a backend implements each in its own file. Arguments")
    out.append("// arrive decoded from the guest's wasm32 layout. A missing method is a compile")
    out.append("// error, which is what keeps a backend complete.\n")
    for name in order:
        if name == "ShimApi":
            out.append("/// Imports that exist only for the guest shim (`guest/src/webgpu_shim.c`).")
        else:
            out.append("/// Raw imports named after the `%s` functions of webgpu.h." % (
                "global" if name == "GlobalApi" else "WGPU" + name[:-3]))
        out.append("pub trait %s {" % name)
        out += traits[name]
        out.append("}\n")
    out.append("/// Everything a backend implements for the guest.")
    out.append("pub trait Api:\n    " + "\n    + ".join(order) + "\n{\n}")
    out.append("impl<T> Api for T where\n    T: " + "\n        + ".join(order) + "\n{\n}\n")
    out.append("// The native host implements all of it.")
    out.append("const _: fn() = || {\n    fn complete<T: Api>() {}\n    complete::<crate::host::Host>();\n};\n")
    out += glue
    out.append("/// Registers every import of the `%s` module." % spec.abi["import_module"])
    out.append("pub(crate) fn register(store: &mut impl AsStoreMut, env: &FunctionEnv<WebGpuEnv>, "
               "exports: &mut Exports) {")
    out += reg
    out.append("}")
    return "\n".join(out) + "\n"


# -- import signature table (shared by the native and JS backends) --------------

def emit_imports(spec):
    out = [BANNER]
    out.append("use super::{ImportSig, ValType::*};\n")
    out.append("pub const IMPORT_MODULE: &str = \"%s\";\n" % spec.abi["import_module"])
    for name, value in spec.abi["event_kinds"]:
        out.append("pub const EVENT_%s: u32 = %d;" % (name.upper(), value))
    out.append("")
    rows = []
    for fn in spec.raw_import_functions():
        params = [t for _, t in spec.lower_params(fn)]
        result = spec.lower_result(fn)
        rows.append((fn.c_name, params, result, fn.c_name in spec.suspending))
    for s in spec.special_imports:
        rows.append((s["name"], [t for _, t in s["params"]], s["result"], s["name"] in spec.suspending))
    out.append("/// Name and core wasm signature of every import, in registration order.")
    out.append("pub static IMPORTS: &[ImportSig] = &[")
    for name, params, result, suspending in rows:
        out.append("    ImportSig { name: \"%s\", params: &[%s], results: &[%s], suspending: %s }," % (
            name, ", ".join(p.upper() for p in params), result.upper() if result else "",
            "true" if suspending else "false"))
    out.append("];")
    return "\n".join(out) + "\n"
