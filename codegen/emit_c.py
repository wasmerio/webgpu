"""Guest-side C outputs: raw import declarations, forwarders, the proc table,
the extension header, and the compile-time ABI checks."""

from spec import pascal, camel, singular

BANNER = "// Generated by codegen/gen.py from spec/webgpu.json and spec/abi.json. Do not edit.\n"


def import_symbol(c_name):
    return "__wgpu_import_" + c_name


def emit_imports_header(spec):
    module = spec.abi["import_module"]
    out = [BANNER]
    out.append("#ifndef WGPU_IMPORTS_GEN_H_\n#define WGPU_IMPORTS_GEN_H_\n")
    out.append("#include <stddef.h>\n#include <stdint.h>\n")
    out.append("#include <webgpu/webgpu.h>\n#include <webgpu/webgpu_wasix.h>\n")
    out.append("#define WGPU_IMPORT_MODULE \"%s\"" % module)
    out.append("#define WGPU_RAW_IMPORT(name) \\\n"
               "    __attribute__((import_module(WGPU_IMPORT_MODULE), import_name(#name)))\n")
    out.append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
    out.append("// The host implements each of these under the name of the webgpu.h function.")
    for f in spec.raw_import_functions():
        out.append("%s WGPU_RAW_IMPORT(%s);" % (f.c_decl(import_symbol(f.c_name)), f.c_name))
    out.append("\n// Imports that exist only for the shim.")
    for s in spec.special_imports:
        if s.get("doc"):
            out.append("// " + s["doc"])
        out.append("%s WGPU_RAW_IMPORT(%s);" % (s["c"] % s["name"], s["name"]))
    out.append("\n// Kinds of event record written by wasmer_wgpu_poll and wasmer_wgpu_wait.")
    out.append("enum {")
    for name, value in spec.abi["event_kinds"]:
        out.append("    WGPU_EVENT_%s = %d," % (name.upper(), value))
    out.append("};\n")
    out.append("#ifdef __cplusplus\n}\n#endif\n")
    out.append("#endif  // WGPU_IMPORTS_GEN_H_")
    return "\n".join(out) + "\n"


def emit_forwarders(spec):
    out = [BANNER]
    out.append("// Every webgpu.h function that needs no guest-side state is a tail call into the host.\n")
    out.append("#include \"wgpu_imports.gen.h\"\n")
    for f in spec.forwarded_functions():
        call = "%s(%s)" % (import_symbol(f.c_name), f.c_call_args())
        body = call if f.c_return() == "void" else "return " + call
        out.append("%s { %s; }" % (f.c_decl(), body))
    return "\n".join(out) + "\n"


def emit_proc_table(spec):
    out = [BANNER]
    out.append("#include <string.h>\n\n#include <webgpu/webgpu.h>\n#include <webgpu/webgpu_wasix.h>\n")
    out.append("typedef struct { const char* name; uint32_t length; WGPUProc proc; } WGPUProcEntry;\n")
    fns = sorted(spec.functions, key=lambda f: f.c_name)
    out.append("static const WGPUProcEntry kProcs[] = {")
    for f in fns:
        out.append("    { \"%s\", %d, (WGPUProc)%s }," % (f.c_name, len(f.c_name), f.c_name))
    out.append("};\n")
    out.append("""WGPUProc wgpuGetProcAddress(WGPUStringView procName) {
    if (procName.data == NULL) return NULL;
    size_t length = procName.length == WGPU_STRLEN ? strlen(procName.data) : procName.length;
    size_t lo = 0, hi = sizeof(kProcs) / sizeof(kProcs[0]);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        const WGPUProcEntry* e = &kProcs[mid];
        size_t n = length < e->length ? length : e->length;
        int cmp = memcmp(procName.data, e->name, n);
        if (cmp == 0) cmp = (length > e->length) - (length < e->length);
        if (cmp == 0) return e->proc;
        if (cmp < 0) hi = mid; else lo = mid + 1;
    }
    return NULL;
}""")
    return "\n".join(out) + "\n"


def emit_extension_header(spec):
    ext = spec.abi["extension"]
    out = ["""/**
 * WASIX extensions to webgpu.h.
 *
 * Generated by codegen/gen.py from spec/abi.json. Do not edit.
 *
 * webgpu.h deliberately says nothing about where a presentable surface comes
 * from. On WASIX the guest has no native window handles, so the host provides
 * the target and the guest names it.
 */

#ifndef WEBGPU_WASIX_H_
#define WEBGPU_WASIX_H_

#include <webgpu/webgpu.h>

#ifdef __cplusplus
extern "C" {
#endif
"""]
    for name, value in ext["stypes"].items():
        out.append("#define WGPUSType_%s ((WGPUSType)0x%08X)" % (pascal(name), int(value, 16)))
    out.append("")
    for s in spec.structs:
        if not s.is_extension_api:
            continue
        out.append("/**\n * %s\n */" % s.doc)
        out.append("typedef struct %s {" % s.c_name)
        out.append("    WGPUChainedStruct chain;")
        for m in s.members:
            if m.ty.doc:
                out.append("    /** %s */" % m.ty.doc)
            out.append("    %s %s;" % (m.ty.c_type(), m.c_name))
        out.append("} %s;\n" % s.c_name)
        init = "WGPU_%s_INIT" % s.name.upper()
        out.append("#define %s _wgpu_MAKE_INIT_STRUCT(%s, { \\" % (init, s.c_name))
        out.append("    /*.chain=*/_wgpu_MAKE_INIT_STRUCT(WGPUChainedStruct, { \\")
        out.append("        /*.next=*/NULL _wgpu_COMMA \\")
        out.append("        /*.sType=*/WGPUSType_%s _wgpu_COMMA \\" % pascal(s.name))
        out.append("    }) _wgpu_COMMA \\")
        for m in s.members:
            default = "WGPU_STRING_VIEW_INIT" if m.ty.kind == "string" else "0"
            out.append("    /*.%s=*/%s _wgpu_COMMA \\" % (m.c_name, default))
        out.append("})\n")
        for alias in ext.get("source_aliases", []):
            if alias["struct"] != s.name:
                continue
            out.append("/**\n * %s\n */" % alias["doc"])
            out.append("typedef %s %s;" % (s.c_name, alias["c_name"]))
            out.append("#define %s ((WGPUSType)0x%08X)" % (alias["stype_c_name"], int(alias["stype"], 16)))
            out.append("#define %s _wgpu_MAKE_INIT_STRUCT(%s, { \\" % (alias["init"], alias["c_name"]))
            out.append("    /*.chain=*/_wgpu_MAKE_INIT_STRUCT(WGPUChainedStruct, { \\")
            out.append("        /*.next=*/NULL _wgpu_COMMA \\")
            out.append("        /*.sType=*/%s _wgpu_COMMA \\" % alias["stype_c_name"])
            out.append("    }) _wgpu_COMMA \\")
            for m in s.members:
                default = "WGPU_STRING_VIEW_INIT" if m.ty.kind == "string" else "0"
                out.append("    /*.%s=*/%s _wgpu_COMMA \\" % (m.c_name, default))
            out.append("})\n")
    for f in spec.functions:
        if not f.is_extension_api:
            continue
        doc = [e for e in ext["functions"] if e["c_name"] == f.c_name][0].get("doc", "")
        if doc:
            out.append("/**\n * %s\n */" % doc)
        out.append("WGPU_EXPORT %s WGPU_FUNCTION_ATTRIBUTE;\n" % f.c_decl())
    out.append("#ifdef __cplusplus\n}  // extern \"C\"\n#endif\n")
    out.append("#endif  // WEBGPU_WASIX_H_")
    return "\n".join(out) + "\n"


def emit_abi_check(spec):
    """Static assertions that pin the generator's layout model to the compiler's."""
    out = [BANNER]
    out.append("// Compiled, never run: proves that sizes, offsets, enum values and import\n"
               "// prototypes computed by the generator are what the compiler sees.\n")
    out.append("#include <stddef.h>\n")
    out.append("#include \"../src/wgpu_imports.gen.h\"\n")
    out.append("#define CHECK(x) _Static_assert(x, #x)\n")
    for s in spec.structs:
        out.append("CHECK(sizeof(%s) == %d);" % (s.c_name, s.size))
        out.append("CHECK(_Alignof(%s) == %d);" % (s.c_name, s.align))
        if s.has_chain_root:
            out.append("CHECK(offsetof(%s, nextInChain) == 0);" % s.c_name)
        if s.kind == "extension":
            out.append("CHECK(offsetof(%s, chain) == 0);" % s.c_name)
        for m in s.members:
            if m.ty.array:
                out.append("CHECK(offsetof(%s, %s) == %d);" % (s.c_name, m.c_count_name, m.offset))
                out.append("CHECK(offsetof(%s, %s) == %d);" % (s.c_name, m.c_name, m.offset + 4))
            else:
                out.append("CHECK(offsetof(%s, %s) == %d);" % (s.c_name, m.c_name, m.offset))
    out.append("")
    for cb in spec.callbacks:
        name = "WGPU" + pascal(cb.name) + "CallbackInfo"
        out.append("CHECK(sizeof(%s) == %d);" % (name, cb.info_size))
        out.append("CHECK(offsetof(%s, userdata2) == %d);" % (name, cb.info_size - 4))
    out.append("")
    for e in spec.enums:
        for entry, value in e.entries:
            out.append("CHECK(%s == 0x%X);" % (e.c_entry(entry), value))
    for b in spec.bitflags:
        for entry, value in b.entries:
            out.append("CHECK(%s_%s == 0x%XULL);" % (b.c_name, pascal(entry), value))
    out.append("CHECK(sizeof(WGPUFlags) == 8);\nCHECK(sizeof(WGPUBool) == 4);\nCHECK(sizeof(void*) == 4);\n")
    out.append("// Each raw import must have the prototype webgpu.h declares for that function.")
    out.append("#define SAME_TYPE(a, b) _Static_assert(__builtin_types_compatible_p(__typeof__(a), __typeof__(b)), #a)")
    for f in spec.raw_import_functions():
        out.append("SAME_TYPE(%s, %s);" % ("__wgpu_import_" + f.c_name, f.c_name))
    out.append("\nint main(void) { return 0; }")
    return "\n".join(out) + "\n"


def emit_link_all(spec):
    """References every public function, so a missing definition fails the link."""
    out = [BANNER]
    out.append("#include <stdio.h>\n\n#include <webgpu/webgpu.h>\n#include <webgpu/webgpu_wasix.h>\n")
    out.append("static void (*const volatile kAll[])(void) = {")
    for f in spec.functions:
        out.append("    (void (*)(void))%s," % f.c_name)
    out.append("};\n")
    out.append("""int main(void) {
    size_t n = sizeof(kAll) / sizeof(kAll[0]);
    size_t resolved = 0;
    for (size_t i = 0; i < n; i++) resolved += kAll[i] != NULL;
    printf("%zu/%zu functions linked\\n", resolved, n);
    WGPUStringView name = { "wgpuDeviceCreateBuffer", WGPU_STRLEN };
    printf("proc lookup: %s\\n", wgpuGetProcAddress(name) == (WGPUProc)wgpuDeviceCreateBuffer ? "ok" : "MISMATCH");
    return resolved == n ? 0 : 1;
}""")
    return "\n".join(out) + "\n"
