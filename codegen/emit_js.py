"""Browser-side outputs: wasm32 struct offsets, enum values, and the import table."""

import json
import os

from spec import ROOT, pascal

BANNER = "// Generated by codegen/gen.py from spec/webgpu.json and spec/abi.json. Do not edit.\n"
SIG = {"i32": "i", "i64": "j", "f32": "f", "f64": "d"}


def js_object(pairs, indent="  "):
    return "{ " + ", ".join("%s: %s" % (k, v) for k, v in pairs) + " }"


def emit_abi(spec):
    out = [BANNER]
    out.append("export const IMPORT_MODULE = %s;\n" % json.dumps(spec.abi["import_module"]))

    out.append("// wasm32 layout of every struct: byte offsets by C member name, plus __size and __align.")
    out.append("export const S = {")
    for s in spec.structs:
        pairs = [("__size", s.size), ("__align", s.align)]
        if s.has_chain_root:
            pairs.append(("nextInChain", 0))
        if s.kind == "extension":
            pairs.append(("chain", 0))
        for m in s.members:
            if m.ty.array:
                pairs.append((m.c_count_name, m.offset))
                pairs.append((m.c_name, m.offset + 4))
            else:
                pairs.append((m.c_name, m.offset))
        out.append("  %s: %s," % (s.c_name, js_object(pairs)))
    for cb in spec.callbacks:
        name = "WGPU" + pascal(cb.name) + "CallbackInfo"
        if cb.style == "callback_mode":
            pairs = [("__size", 20), ("nextInChain", 0), ("mode", 4), ("callback", 8), ("userdata1", 12),
                     ("userdata2", 16)]
        else:
            pairs = [("__size", 16), ("nextInChain", 0), ("callback", 4), ("userdata1", 8), ("userdata2", 12)]
        out.append("  %s: %s," % (name, js_object(pairs)))
    out.append("  WGPUStringView: { __size: 8, __align: 4, data: 0, length: 4 },")
    out.append("  WGPUChainedStruct: { __size: 8, __align: 4, next: 0, sType: 4 },")
    out.append("};\n")

    out.append("// C enum values by entry name.")
    out.append("export const E = {")
    for e in spec.enums:
        pairs = [(pascal(n) if not pascal(n)[0].isdigit() else json.dumps(pascal(n)), v) for n, v in e.entries]
        out.append("  %s: %s," % (pascal(e.name), js_object(pairs)))
    out.append("};\n")

    out.append("// Bitflag values (64-bit in C; every defined bit fits in 32).")
    out.append("export const F = {")
    for b in spec.bitflags:
        pairs = [(pascal(n), v) for n, v in b.entries]
        out.append("  %s: %s," % (pascal(b.name), js_object(pairs)))
    out.append("};\n")

    out.append("// sType values, including the ones webgpu_wasix.h adds.")
    out.append("export const STYPE = {")
    for n, v in spec.enum_by_name["s_type"].entries:
        out.append("  %s: 0x%X," % (pascal(n), v))
    for n, v in sorted(spec.extension_stypes.items()):
        out.append("  %s: 0x%X," % (pascal(n), v))
    for v, n in sorted(spec.stype_aliases.items()):
        out.append("  %sAlias: 0x%X," % (pascal(n), v))
    out.append("};\n")

    out.append("export const EVENT = {")
    for name, value in spec.abi["event_kinds"]:
        out.append("  %s: %d," % (pascal(name), value))
    out.append("};\n")

    out.append("// [name, parameter types, result type, suspending]; i=i32 j=i64 f=f32 d=f64.")
    out.append("export const IMPORTS = [")
    for fn in spec.raw_import_functions():
        params = "".join(SIG[t] for _, t in spec.lower_params(fn))
        result = spec.lower_result(fn)
        out.append("  [%s, %s, %s, %s]," % (json.dumps(fn.c_name), json.dumps(params),
                                         json.dumps(SIG[result] if result else ""),
                                         "true" if fn.c_name in spec.suspending else "false"))
    for s in spec.special_imports:
        params = "".join(SIG[t] for _, t in s["params"])
        out.append("  [%s, %s, %s, %s]," % (json.dumps(s["name"]), json.dumps(params),
                                         json.dumps(SIG[s["result"]] if s["result"] else ""),
                                         "true" if s["name"] in spec.suspending else "false"))
    out.append("];\n")

    webidl = os.path.join(ROOT, "spec", "webidl_enums.json")
    if os.path.exists(webidl):
        with open(webidl) as f:
            tables = json.load(f)
        out.append("// WebIDL enum strings by C enum value (spec/webidl_enums.json).")
        out.append("export const WEBIDL = {")
        for name in sorted(tables):
            if name.startswith("_"):
                continue
            entries = tables[name]
            pairs = ", ".join("%s: %s" % (k, json.dumps(v)) for k, v in sorted(entries.items(), key=lambda kv: int(kv[0])))
            out.append("  %s: { %s }," % (name, pairs))
        out.append("};")
    else:
        out.append("export const WEBIDL = {};")
    return "\n".join(out) + "\n"
